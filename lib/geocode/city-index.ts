export const staticCities = cityRows.map(([name, country, latitude, longitude, aliases = []]) => ({
  name,
  country,
  latitude,
  longitude,
  aliases,
  timezone: tzLookup(latitude, longitude),
}));

export type StaticCityResult = {
  label: string;
  city: string;
  latitude: number;
  longitude: number;
  timezone: string;
};

function normalize(value: string) {
  return value.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase().replace(/\s+/g, " ").trim();
}

export function findStaticCities(query: string): StaticCityResult[] {
  const normalizedQuery = normalize(query);
  return staticCities
    .map((place) => {
      const searchableNames = [place.name, ...place.aliases].map(normalize);
      const searchable = normalize(`${place.name} ${place.country}`);
      const rank = searchableNames.includes(normalizedQuery) ? 0
        : searchableNames.some((name) => name.startsWith(normalizedQuery)) ? 1
          : searchable.includes(normalizedQuery) ? 2 : -1;
      return { place, rank };
    })
    .filter(({ rank }) => rank >= 0)
    .sort((left, right) => left.rank - right.rank)
    .slice(0, 6)
    .map(({ place }) => ({
      label: `${place.name}, ${place.country}`,
      city: `${place.name}, ${place.country}`,
      latitude: place.latitude,
      longitude: place.longitude,
      timezone: place.timezone,
    }));
}
